"""
Builds the fonts used by the hybrid vector PDF mode.

Source: Noto Sans / Noto Sans Mono (SIL Open Font License 1.1, see fonts/OFL.txt).
Each font is subset to Latin, Greek, Cyrillic and common symbols, hinting and
OpenType layout tables are removed (the plugin places every word itself), then
the result is zlib-compressed and written as base64 to src/pdf/fonts-data.ts.
Characters outside these subsets (CJK, Arabic, emoji...) are rendered as small
images with an invisible text layer, so they are still copyable.

Usage: python3 scripts/make-fonts.py [noto-font-dir]   (requires fonttools)
"""
import base64, io, os, sys, zlib

# fontTools uses sets internally: fix the hash seed for byte-identical output
if os.environ.get("PYTHONHASHSEED") != "0":
    os.environ["PYTHONHASHSEED"] = "0"
    os.execv(sys.executable, [sys.executable] + sys.argv)

from fontTools import subset
from fontTools.ttLib import TTFont

SRC = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/noto"
ROOT = os.path.join(os.path.dirname(__file__), "..")
FONTS = {
    "sans-regular": "NotoSans-Regular.ttf",
    "sans-bold": "NotoSans-Bold.ttf",
    "sans-italic": "NotoSans-Italic.ttf",
    "sans-bolditalic": "NotoSans-BoldItalic.ttf",
    "mono-regular": "NotoSansMono-Regular.ttf",
    "mono-bold": "NotoSansMono-Bold.ttf",
}
RANGES = [
    (0x20, 0x7E), (0xA0, 0x24F), (0x2B0, 0x36F), (0x370, 0x3FF), (0x400, 0x52F),
    (0x1E00, 0x1EFF), (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F),
    (0x2150, 0x218F), (0x2190, 0x21FF), (0x2200, 0x22FF), (0x2300, 0x23FF),
    (0x2500, 0x25FF), (0xFFFD, 0xFFFD),
]

def build(path):
    opts = subset.Options()
    opts.hinting = False
    opts.layout_features = []
    opts.drop_tables += ["GSUB", "GPOS", "GDEF", "kern", "DSIG", "STAT", "MVAR", "HVAR", "gasp", "meta"]
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6]
    opts.notdef_outline = True
    opts.recalc_timestamp = False
    font = TTFont(path, recalcTimestamp=False)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=[c for lo, hi in RANGES for c in range(lo, hi + 1)])
    sub.subset(font)
    font["head"].created = font["head"].modified = 0
    buf = io.BytesIO(); font.save(buf)
    return buf.getvalue()

lines = [
    "// Generated by scripts/make-fonts.py — do not edit.",
    "// Noto Sans / Noto Sans Mono subsets, SIL Open Font License 1.1 (fonts/OFL.txt).",
    "// Each value is a zlib-compressed TrueType font, base64-encoded.",
    "export const FONT_DATA: Record<string, string> = {",
]
total = 0
for key, file in FONTS.items():
    data = build(os.path.join(SRC, file))
    packed = zlib.compress(data, 9)
    total += len(packed)
    lines.append(f'  "{key}": "{base64.b64encode(packed).decode()}",')
    print(f"{key:16} {len(data)//1024:4} KB -> {len(packed)//1024:4} KB compressed")
lines.append("};")
with open(os.path.join(ROOT, "src", "pdf", "fonts-data.ts"), "w") as f:
    f.write("\n".join(lines) + "\n")
print(f"total {total//1024} KB compressed")
