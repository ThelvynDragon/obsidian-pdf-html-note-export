"""
Generates src/pdf/glyphless-font.ts: a tiny TrueType font with a single
empty glyph, embedded as base64 (same idea as Tesseract's "GlyphLessFont").

The font is only used for the invisible text layer of exported PDFs. Shapes
are never drawn; copy/search correctness comes from the ToUnicode CMap that
the plugin writes for each PDF, so every script and emoji is supported.

Usage: python3 scripts/make-glyphless-font.py   (requires fonttools)
"""
import base64, io, os
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

glyphs = [".notdef", "blank"]
empty = TTGlyphPen(None).glyph()
fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(glyphs)
fb.setupCharacterMap({0x20: "blank"})
fb.setupGlyf({g: empty for g in glyphs})
fb.setupHorizontalMetrics({g: (500, 0) for g in glyphs})
fb.setupHorizontalHeader(ascent=800, descent=-200)
fb.setupNameTable({"familyName": "GlyphLessFont", "styleName": "Regular"})
fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
fb.setupPost(keepGlyphNames=False)
fb.font["head"].created = fb.font["head"].modified = 0  # reproducible output

buf = io.BytesIO(); fb.save(buf); data = buf.getvalue()
out = os.path.join(os.path.dirname(__file__), "..", "src", "pdf", "glyphless-font.ts")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as f:
    f.write("// Generated by scripts/make-glyphless-font.py — do not edit.\n")
    f.write("// One empty glyph; see the script for details.\n")
    f.write(f'export const GLYPHLESS_FONT_BASE64 =\n  "{base64.b64encode(data).decode()}";\n')
print(f"{len(data)} bytes -> {out}")
